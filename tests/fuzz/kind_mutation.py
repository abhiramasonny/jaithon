# Dynamic locals.
#
# Every shape above writes each local ONCE, from one source, so no program the
# matrix generates has ever produced what the tier calls a "dynamic local": a
# single slot written with two different kinds at two points in one body. That
# forces the slot out of a register into frame memory behind a runtime type tag
# (`dynamicLocal[slot]`), and routes every read of it through `localIn`'s guard
# block in src/vm/jit/jit_func.c. Three of the confirmed miscompiles this
# fuzzer exists to catch lived in exactly that block -- SLOT_LIST, SLOT_INST
# and SLOT_MAYBE_INST dynamic locals, all three cases of `localTagFor` mapping
# distinct object kinds onto the same VAL_OBJ tag -- and the matrix above
# cannot reach it however EARLY/LATE are tuned, because it never writes one
# local twice.
#
# This is a separate generation path rather than more SHAPES rows because the
# shape genuinely differs: two writes instead of one, self-recursion in two of
# them, and the thing whose kind changes is an ARGUMENT rather than an element
# of a container. The bodies are copied structurally from
# tests/golden/jit_dynamic_local_{list,inst,maybe_inst}.jai -- the regression
# tests for those three bugs -- rather than invented, and each one's compiled
# `insts` matches its golden's exactly (284/668/2048/2512), which is the check
# that the copy kept the property that mattered.
DYN_PRELUDE = """#: Generated by tests/fuzz/kind_mutation.py. Do not edit.
#: `Dog.legs` and `Bird.wings` share a byte offset, and `Bird` has its own
#: `legs` at a different one: reading a Bird through Dog's layout yields 99
#: rather than 2, so a missed class guard is a wrong NUMBER, not a raise.
#: `Cat` is the same trap one step further out -- it has `legs` too, at yet
#: another offset -- so it stays a wrong number even for the late mutation.
class Dog {
    pub var legs: int = 4
    pub var link: any = null
}

class Bird {
    pub var wings: int = 99
    pub var legs: int = 2
}

class Cat {
    pub var tail: int = 1
    pub var whiskers: int = 12
    pub var legs: int = 77
}

class Holder {
    pub var n: int
    fn init(self, n: int) { self.n = n }
}
"""

