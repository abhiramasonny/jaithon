#!/usr/bin/env python3
"""Differential fuzzer for kind stability in the compiled tier.

Both silent miscompiles found on 2026-08-12 had the same shape: the tier samples
a value's kind while a loop is warming, specialises the compiled body to it, and
the program then puts a different kind there. The compiled code read the new
value's payload under the old value's tag.

  - a `str` in a list sampled as int bound the string's POINTER as an integer
    (41080394656 where the interpreter raises TypeError)
  - a `bool` local at an OSR entry was read eight bytes wide, so `if flag {`
    took the wrong arm

Neither was caught by anything. This generates the whole matrix -- container and
field shapes x the kind that arrives late x what the body does with it -- runs
each program four ways, and diffs. The interpreter is the oracle; the compiled
tier must either agree with it or deopt to it.

A second family (DYN_SHAPES, further down) does the same for a local written
with two different kinds in one body -- a "dynamic local", which is stored in
the frame behind a runtime tag and read through `localIn`'s guard block. Three
more confirmed miscompiles lived there, and nothing the matrix above generates
reaches it, since every shape there writes each local exactly once.

    python3 tests/fuzz/kind_mutation.py            # the standard matrix
    python3 tests/fuzz/kind_mutation.py --keep     # leave the .jai files behind
    python3 tests/fuzz/kind_mutation.py --warm 20000

Exit status is non-zero if any program disagrees, so it can be a gate.
"""

