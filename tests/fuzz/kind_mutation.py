# What arrives in the dynamic slot once the body is compiled. A superset of
# KINDS: `dict` and the two extra classes exist because the bugs here were all
# object kinds colliding under one value tag, so the object side is where the
# resolution has to be finest. `inst_nofield` has neither `legs` nor an index
# (the interpreter raises, and a missed guard shows up as a number instead);
# `inst_offset` has `legs` at a third offset, so both sides return a number and
# only the VALUE separates them.
DYN_LATE = {
    "int": "7",
    "float": "0.5",
    "bool": "true",
    "str": '"s"',
    "null": "null",
    "list": "[10, 20, 30]",
    "dict": "{0: 99}",
    "inst_nofield": "Holder(3)",
    "inst_offset": "Cat()",
}

DYN_ATTEMPT = """
fn attempt(seed: any, n: int, other: any) -> str {
    try {
        return f"{probe(seed, n, other)}"
    } catch e: TypeError {
        return "TypeError"
    } catch e: ValueError {
        return "ValueError"
    } catch e: Error {
        return "Error"
    }
}
"""

DYN_MAIN = """
fn main() -> int {
SEED    let mid: any = MID
    let late: any = LATE
    var warm = ""
    for _r in 0..WARM { warm = attempt(seed, 3, mid) }
    print(warm)
    print(attempt(seed, 3, late))
    print(attempt(seed, 3, late))
EXTRA    return 0
}
"""

ATTEMPT = """
#: Every wrong-kind outcome the interpreter can produce is a raise, so both
#: sides have to be able to print one. Anything that is NOT a raise and NOT the
#: interpreter's number is a miscompile.
#:
#: The base `Error` catch is required once a consumer can raise something
#: other than TypeError/ValueError -- `x.n`/`x.len()` on a value that has
#: neither raises AttributeError, and an uncaught raise here does not just
#: mis-score one case, it aborts `main()` on the FIRST attempt() call that
#: hits it, so the second and third calls (the ones actually holding the
#: mutated LATE kind) never run at all and the case silently loses coverage
#: rather than failing loudly.
fn attempt(c: any) -> str {
    try {
        return probe(c)
    } catch e: TypeError {
        return "TypeError"
    } catch e: ValueError {
        return "ValueError"
    } catch e: Error {
        return "Error"
    }
}
"""


def program(shape, consumer, early, late, warm):
    body = SHAPES[shape].replace("CONSUMER", CONSUMERS[consumer])
    main = (BUILDERS[shape]
            .replace("EARLY", KINDS[early])
            .replace("LATE", KINDS[late])
            .replace("WARM", str(warm)))
    return PRELUDE + body + ATTEMPT + main


def dyn_program(shape, late, warm):
    main = (DYN_MAIN
            .replace("SEED", DYN_SEEDS[shape])
            .replace("MID", DYN_MIDS[shape])
            .replace("LATE", DYN_LATE[late])
            .replace("WARM", str(warm))
            .replace("EXTRA", DYN_EXTRA.get(shape, "")))
    return DYN_PRELUDE + DYN_SHAPES[shape] + DYN_ATTEMPT + main


def gc_flag():
    """`--gc-stress=N` postdates this fuzzer's first use.

    Probing for it means the fuzzer can be pointed at an OLDER binary, which is
    the only way to prove it has teeth: build the tree from before a fix, run
    the matrix, and watch the cases that fix addressed light up. Without this
    every case "fails" on a CLI usage error and the signal is lost in it.
    """
    env = dict(os.environ)
    env["JAITHON_PATH"] = os.path.join(ROOT, "lib")
    done = subprocess.run([JAITHON, "--help"], capture_output=True, env=env)
    text = (done.stdout + done.stderr).decode("utf-8", "replace")
    return "--gc-stress[=N]" in text and "--gc-stress=64" or "--gc-stress"


MODES = [
    ("interp", {"JAITHON_NO_JIT": "1"}, []),
    ("jit", {}, []),
    ("deopt", {"JAITHON_JIT_DEOPT_STRESS": "1"}, []),
    ("gc", {}, [gc_flag()]),
]


def run(path, env_extra, flags, timeout):
    env = dict(os.environ)
    env["JAITHON_PATH"] = os.path.join(ROOT, "lib")
    env.update(env_extra)
    try:
        done = subprocess.run([JAITHON, "run"] + flags + [path],
                              capture_output=True, env=env, timeout=timeout)
    except subprocess.TimeoutExpired:
        return "<timeout>"
    return (done.stdout + done.stderr).decode("utf-8", "replace").strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--warm", type=int, default=8000,
                    help="loop repetitions before the kind changes")
    ap.add_argument("--timeout", type=int, default=120)
    ap.add_argument("--keep", action="store_true",
                    help="keep generated .jai files for inspection")
    ap.add_argument("--filter", default="",
                    help="only run cases whose name contains this")
    args = ap.parse_args()

    if not os.access(JAITHON, os.X_OK):
        print(f"error: {JAITHON} not built. Run 'make' first.", file=sys.stderr)
        return 2

    # (name, source). Both families land in one list so the run loop, the
    # --filter and the reporting stay single-path.
    cases = []
    for shape in SHAPES:
        for consumer in CONSUMERS:
            if consumer in CONSUMER_KINDS and shape not in OBJECT_CONSUMER_SHAPES:
                continue
            for early in CONSUMER_KINDS.get(consumer, ("int", "float")):
                for late in KINDS:
                    if late == early:
                        continue
                    cases.append((f"{shape}-{consumer}-{early}-to-{late}",
                                  program(shape, consumer, early, late, args.warm)))
    for shape in DYN_SHAPES:
        for late in DYN_LATE:
            cases.append((f"{shape}-to-{late}",
                          dyn_program(shape, late, args.warm)))

    outdir = tempfile.mkdtemp(prefix="kindfuzz-")
    ran = skipped = 0
    failures = []

    for name, source in cases:
        if args.filter and args.filter not in name:
            continue
        path = os.path.join(outdir, name.replace("-", "_") + ".jai")
        with open(path, "w") as f:
            f.write(source)

        results = {}
        for mode, env_extra, flags in MODES:
            results[mode] = run(path, env_extra, flags, args.timeout)

        # A program the interpreter itself cannot run is a bad generator case,
        # not a finding -- report it as skipped rather than pretending it passed.
        if "error[" in results["interp"] or results["interp"] == "<timeout>":
            skipped += 1
            continue

        ran += 1
        oracle = results["interp"]
        bad = [m for m in ("jit", "deopt", "gc") if results[m] != oracle]
        if bad:
            failures.append((name, path, oracle, {m: results[m] for m in bad}))

    for name, path, oracle, got in failures:
        print(f"MISMATCH {name}")
        print(f"  interp: {oracle!r}")
        for mode, value in got.items():
            print(f"  {mode:>6}: {value!r}")
        print(f"  program: {path}")

    print(f"kind-mutation fuzz: {ran} cases, {len(failures)} mismatched, "
          f"{skipped} skipped (interpreter rejected)")
    if not failures and not args.keep:
        # rmtree, not unlink: running a program leaves a __jaicache__ DIRECTORY
        # next to it.
        shutil.rmtree(outdir, ignore_errors=True)
    elif failures:
        print(f"generated programs kept in {outdir}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
